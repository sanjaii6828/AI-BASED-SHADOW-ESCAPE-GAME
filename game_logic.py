# ============================================================

from map_data import EXIT


def check_game(
    player,
    guards,
    keys
):

    # ========================================================
    # LOSS
    # ========================================================

    if player in guards:

        return True, "LOSS"


    # ========================================================
    # WIN
    # ========================================================

    if (
        player == EXIT
        and
        len(keys) == 0
    ):

        return True, "WIN"


    # ========================================================
    # GAME CONTINUES
    # ========================================================

    return False, ""