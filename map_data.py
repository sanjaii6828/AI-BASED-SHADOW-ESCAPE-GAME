# ============================================================
# GAME MAP DATA
# ============================================================

from settings import COLS, ROWS


# ============================================================
# WALLS
# ============================================================

walls = set()


# Outer boundary
for x in range(COLS):
    walls.add((x, 0))
    walls.add((x, ROWS - 1))


for y in range(ROWS):
    walls.add((0, y))
    walls.add((COLS - 1, y))


# ============================================================
# CRATES
# ============================================================

crates = [
    (2, 18, 5, 21),
    (9, 14, 13, 17),
    (11, 16, 15, 19)
]


for x1, y1, x2, y2 in crates:

    for x in range(x1, x2 + 1):

        for y in range(y1, y2 + 1):

            walls.add((x, y))


# ============================================================
# CARS
# ============================================================

cars = [
    (20, 11, 8, 3),
    (16, 15, 4, 8)
]


for x, y, w, h in cars:

    for cx in range(x, x + w):

        for cy in range(y, y + h):

            walls.add((cx, cy))


